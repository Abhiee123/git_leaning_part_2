def get_response(user_input):
    if user_input.lower() == "hi":
        return "Hi there! 👋"
    return "I'm Branch 1 bot."

def main():
    print("ChatBot v2 - Branch 1")
    while True:
        user_input = input("You: ")
        response = get_response(user_input)
        print("Bot:", response)

if __name__ == "__main__":
    main()

